const NEPALI_DIGITS = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"]

function language(nepali) {
  return nepali ? "ne" : "en"
}

// Convert a JavaScript Date to { year, month, day, weekday } in BS, or null
// when the date falls outside the table.
export function adToBs(value) {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return null

  const utc = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate())
  let days = Math.round((utc - BS_EPOCH_UTC) / MS_PER_DAY) + 1
  if (days < 1) return null

  let year = BS_START_YEAR

  for (let index = 0; index < BS_MONTH_DAYS.length; index += 1) {
    const yearDays = BS_MONTH_DAYS[index].reduce((sum, daysInMonth) => sum + daysInMonth, 0)

    if (days <= yearDays) {
      year = BS_START_YEAR + index
      break
    }

    days -= yearDays

    if (index === BS_MONTH_DAYS.length - 1) return null
  }

  const monthDays = BS_MONTH_DAYS[year - BS_START_YEAR]
  let month = 0

  while (month < monthDays.length && days > monthDays[month]) {
    days -= monthDays[month]
    month += 1
  }

  return { year, month: month + 1, day: days, weekday: date.getDay() }
}

export function bsMonthName(month, { short = false, nepali = false } = {}) {
  return MONTHS[language(nepali)][short ? "short" : "long"][month - 1] || ""
}

export function bsWeekdayName(weekday, { short = false, nepali = false } = {}) {
  return WEEKDAYS[language(nepali)][short ? "short" : "long"][weekday] || ""
}

export function bsNumber(value, nepali = false) {
  const text = String(value)
  if (!nepali) return text

  return text.replace(/\d/g, (digit) => NEPALI_DIGITS[Number(digit)])
}

export function bsMonthKey(bs) {
  return `${bs.year}-${String(bs.month).padStart(2, "0")}`
}
